"""
Jenkins status MCP resources.

Provides access to Jenkins status data through MCP resources.
"""

import structlog

logger = structlog.get_logger()


async def get_system_status() -> str:
    """Get Jenkins system status."""
    try:
        from ..server import get_jenkins_client
        client = get_jenkins_client()

        system_info = await client.get_system_info(include_stats=True)
        queue_info = await client.get_build_queue()

        return f"""# Jenkins System Status

## System Information
- **Mode**: {system_info.get('mode', 'UNKNOWN')}
- **Description**: {system_info.get('description', 'Jenkins')}
- **URL**: {system_info.get('url', 'Unknown')}

## Executors
- **Total Executors**: {system_info.get('numExecutors', 0)}
- **Busy Executors**: {system_info.get('busyExecutors', 0)}

## Build Queue
- **Queue Length**: {len(queue_info.get('queue_items', []))}
- **Items in Queue**: {', '.join([item.get('job', {}).get('name', 'Unknown') for item in queue_info.get('queue_items', [])[:5]])}

Generated by Jenkins MCP Server
"""

    except Exception as e:
        logger.error("failed_to_get_system_status", error=str(e))
        return f"Error retrieving system status: {str(e)}"


async def get_job_status(job_name: str) -> str:
    """Get Jenkins job status."""
    try:
        from ..server import get_jenkins_client
        client = get_jenkins_client()

        job_details = await client.get_job_details(job_name=job_name)

        last_build = job_details.get("lastBuild", {})
        last_completed_build = job_details.get("lastCompletedBuild", {})

        return f"""# Job Status: {job_name}

## Job Information
- **Name**: {job_details.get('name', job_name)}
- **Display Name**: {job_details.get('displayName', job_name)}
- **URL**: {job_details.get('url', 'Unknown')}
- **Buildable**: {job_details.get('buildable', False)}
- **In Queue**: {job_details.get('inQueue', False)}
- **Concurrent Build**: {job_details.get('concurrentBuild', False)}

## Last Build
- **Number**: {last_build.get('number', 'N/A')}
- **Result**: {last_build.get('result', 'N/A')}
- **URL**: {last_build.get('url', 'N/A')}

## Last Completed Build
- **Number**: {last_completed_build.get('number', 'N/A')}
- **Result**: {last_completed_build.get('result', 'N/A')}
- **URL**: {last_completed_build.get('url', 'N/A')}

## Next Build Number
- **Next Build**: #{job_details.get('nextBuildNumber', 'N/A')}

Generated by Jenkins MCP Server
"""

    except Exception as e:
        logger.error("failed_to_get_job_status", job_name=job_name, error=str(e))
        return f"Error retrieving job status for '{job_name}': {str(e)}"


