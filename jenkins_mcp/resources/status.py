async def get_queue_status() -> str:
    """Get Jenkins build queue status."""
    try:
        from ..server import get_jenkins_client
        client = get_jenkins_client()

        queue_info = await client.get_build_queue()
        queue_items = queue_info.get('queue_items', [])

        return f"""# Build Queue Status

## Queue Summary
- **Total Items**: {len(queue_items)}
- **Status**: {'Active' if queue_items else 'Empty'}

## Queue Items
{chr(10).join([f"### {item.get('job', {}).get('name', 'Unknown Job')}" + chr(10) +
               f"- **ID**: {item.get('id', 'Unknown')}" + chr(10) +
               f"- **Why**: {item.get('why', 'Unknown reason')}" + chr(10) +
               f"- **Stuck**: {item.get('stuck', False)}" + chr(10) +
               f"- **Blocked**: {item.get('blocked', False)}" + chr(10) +
               f"- **Buildable**: {item.get('buildable', False)}" + chr(10) +
               f"- **Waiting**: {item.get('waiting', False)}"
               for item in queue_items[:10]])}

Generated by Jenkins MCP Server
"""

    except Exception as e:
        logger.error("failed_to_get_queue_status", error=str(e))
        return f"Error retrieving queue status: {str(e)}"


async def get_nodes_status() -> str:
    """Get Jenkins nodes status."""
    try:
        from ..server import get_jenkins_client
        client = get_jenkins_client()

        nodes_info = await client.list_nodes(include_details=True)
        nodes = nodes_info.get('nodes', [])

        return f"""# Nodes Status

## Summary
- **Total Nodes**: {nodes_info.get('total_count', 0)}
- **Online Nodes**: {nodes_info.get('online_count', 0)}
- **Offline Nodes**: {nodes_info.get('offline_count', 0)}

## Node Details
{chr(10).join([f"### {node.get('displayName', 'Unknown Node')}" + chr(10) +
               f"- **Status**: {'🟢 Online' if not node.get('offline', True) else '🔴 Offline'}" + chr(10) +
               f"- **Idle**: {'Yes' if node.get('idle', True) else 'No'}" + chr(10) +
               f"- **Executors**: {node.get('numExecutors', 0)}" + chr(10) +
               f"- **Description**: {node.get('description', 'No description')}" + chr(10) +
               f"- **URL**: {node.get('url', 'Unknown')}"
               for node in nodes])}

Generated by Jenkins MCP Server
"""

    except Exception as e:
        logger.error("failed_to_get_nodes_status", error=str(e))
        return f"Error retrieving nodes status: {str(e)}"